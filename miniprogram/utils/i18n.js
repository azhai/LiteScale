function strings(lang) {
  return DICT[lang] || DICT.zh;
}

function bmiCategory(bmi, lang) {
  const s = strings(lang);
  if (bmi < 18.5) return s.underweight;
  if (bmi < 25) return s.normal;
  if (bmi < 30) return s.overweight;
  return s.obese;
}

function importResult(count, lang) {
  return lang === 'en' ? `Imported ${count} record(s)` : `已导入 ${count} 条记录`;
}

module.exports = { strings, bmiCategory, importResult };
